/**
 * Downloads the company's own photographs from the legacy Webnode galleries,
 * normalises them (orientation, size, progressive JPEG) into /public/proyectos
 * and emits src/data/photos.generated.ts with real intrinsic dimensions.
 *
 *   node scripts/ingest-photos.mjs <photos.json> [--force]
 */
import { mkdirSync, writeFileSync, existsSync, readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = join(root, "public", "proyectos");
const manifestPath = process.argv[2];
const force = process.argv.includes("--force");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36";

/** legacy gallery slug -> the category this site groups it under */
const CATEGORY_OF = {
  "puertas-de-entrada": "puertas",
  "puertas-de-paso": "puertas",
  vestidores: "vestidores",
  otros: "vestidores",
  ventanas: "exteriores",
  pergolas: "exteriores",
  "pasa-manos": "exteriores",
  "muebles-de-bano": "banos",
};

/** human label for the specific piece of work, per legacy gallery */
const KIND_OF = {
  "puertas-de-entrada": "Puerta de entrada",
  "puertas-de-paso": "Puerta de paso",
  vestidores: "Vestidor a medida",
  otros: "Mobiliario a medida",
  ventanas: "Ventana de madera",
  pergolas: "Pérgola",
  "pasa-manos": "Pasamanos",
  "muebles-de-bano": "Mueble de baño",
};

mkdirSync(OUT_DIR, { recursive: true });

const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
const records = [];
let n = 0;

for (const [gallery, data] of Object.entries(manifest)) {
  let i = 0;
  for (const photo of data.photos) {
    i += 1;
    const slug = `${gallery}-${String(i).padStart(2, "0")}`;
    const outFile = join(OUT_DIR, `${slug}.jpg`);

    if (force || !existsSync(outFile)) {
      let buf = null;
      for (const url of [photo.full, photo.preview]) {
        try {
          const res = await fetch(url, { headers: { "User-Agent": UA } });
          if (!res.ok) continue;
          const candidate = Buffer.from(await res.arrayBuffer());
          // prefer the full-size original; fall back to the thumbnail
          if (candidate.length > 2000) {
            buf = candidate;
            break;
          }
        } catch {
          /* try next url */
        }
      }
      if (!buf) {
        console.warn(`  !! could not fetch ${slug}`);
        continue;
      }

      await sharp(buf)
        .rotate() // honour EXIF orientation
        .resize({ width: 2000, height: 2000, fit: "inside", withoutEnlargement: true })
        .jpeg({ quality: 82, progressive: true, mozjpeg: true, chromaSubsampling: "4:4:4" })
        .toFile(outFile);
    }

    const meta = await sharp(outFile).metadata();
    records.push({
      id: slug,
      src: `/proyectos/${slug}.jpg`,
      width: meta.width,
      height: meta.height,
      orientation: meta.width >= meta.height ? "landscape" : "portrait",
      category: CATEGORY_OF[gallery],
      gallery,
      kind: KIND_OF[gallery],
      index: i,
    });
    n += 1;
    if (n % 10 === 0) process.stdout.write(`  …${n}\n`);
  }
}

records.sort((a, b) => a.id.localeCompare(b.id));

const ts = `// AUTO-GENERATED by scripts/ingest-photos.mjs — do not edit by hand.
// Source: the company's own photographs, migrated from the legacy Webnode galleries.

export type PhotoOrientation = "landscape" | "portrait";

export type Photo = {
  id: string;
  src: string;
  width: number;
  height: number;
  orientation: PhotoOrientation;
  /** grouping used by this site's service pages */
  category: "puertas" | "vestidores" | "exteriores" | "banos";
  /** original legacy gallery the photograph came from */
  gallery: string;
  /** what the photograph shows */
  kind: string;
  index: number;
};

export const photos: Photo[] = ${JSON.stringify(records, null, 2)};
`;

mkdirSync(join(root, "src", "data"), { recursive: true });
writeFileSync(join(root, "src", "data", "photos.generated.ts"), ts);

const byCat = records.reduce((acc, r) => ((acc[r.category] = (acc[r.category] || 0) + 1), acc), {});
const land = records.filter((r) => r.orientation === "landscape").length;
console.log(`\n${records.length} photographs ready in public/proyectos`);
console.log(`landscape ${land} / portrait ${records.length - land}`);
console.log("by category:", byCat);
console.log(
  "widest:",
  [...records].sort((a, b) => b.width - a.width).slice(0, 8).map((r) => `${r.id}(${r.width}x${r.height})`).join(" ")
);
